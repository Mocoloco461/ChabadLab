def _norm(s):
    return " ".join(s.replace("״", '"').replace("׳", "'").split())


# form -> group index; and max form length in words
INDEX = {}
for gi, g in enumerate(GROUPS):
    for f in g:
        INDEX.setdefault(_norm(f), set()).add(gi)
MAX_WORDS = max(len(f.split()) for f in INDEX)


def alternatives(words):
    """If the word sequence is a known form, return all equivalent forms (incl. itself)."""
    key = _norm(" ".join(words))
    groups = INDEX.get(key)
    if not groups:
        return None
    alts = []
    for gi in sorted(groups):
        for f in GROUPS[gi]:
            f = _norm(f)
            if f not in alts:
                alts.append(f)
    return alts
